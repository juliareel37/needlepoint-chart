import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, "..");
const csvPath = path.join(repoRoot, "data", "thread-colors.csv");
const outputPath = path.join(repoRoot, "lib", "dmcColors.generated.ts");

const REQUIRED_HEADERS = [
  "id_dmc",
  "hex_code",
  "family_dmc",
  "family_new",
  "name_dmc",
  "name_maxx",
  "updated_dt",
];

async function main() {
  const csv = await fs.readFile(csvPath, "utf8");
  const rows = parseCsv(csv);

  if (rows.length === 0) {
    throw new Error("thread-colors.csv is empty");
  }

  const headers = rows[0];
  assertHeaders(headers);

  const records = rows.slice(1).filter((row) => row.some((value) => value.trim().length > 0));
  const colors = records.map((row, index) => toColorRecord(headers, row, index + 2));

  const output = `${GENERATED_HEADER}
import type { DmcColor } from "./dmcColors";

export const DMC_COLORS: DmcColor[] = [
${colors.map((color) => `  ${formatColor(color)},`).join("\n")}
];
`;

  await fs.writeFile(outputPath, output);
}

function assertHeaders(headers) {
  const normalized = headers.map((header) => header.trim());

  if (normalized.length !== REQUIRED_HEADERS.length) {
    throw new Error(`Expected ${REQUIRED_HEADERS.length} CSV headers, received ${normalized.length}`);
  }

  for (let index = 0; index < REQUIRED_HEADERS.length; index += 1) {
    if (normalized[index] !== REQUIRED_HEADERS[index]) {
      throw new Error(
        `Unexpected CSV header at column ${index + 1}: expected "${REQUIRED_HEADERS[index]}", received "${normalized[index]}"`,
      );
    }
  }
}

function toColorRecord(headers, row, lineNumber) {
  if (row.length !== headers.length) {
    throw new Error(
      `CSV row ${lineNumber} has ${row.length} columns; expected ${headers.length}`,
    );
  }

  const record = Object.fromEntries(
    headers.map((header, index) => [header, row[index]?.trim() ?? ""]),
  );
  if (!record.id_dmc) {
    throw new Error(`CSV row ${lineNumber} is missing a code`);
  }

  if (!record.name_dmc) {
    throw new Error(`CSV row ${lineNumber} is missing a name`);
  }

  if (!record.family_new) {
    throw new Error(`CSV row ${lineNumber} is missing family_new`);
  }

  if (!/^#[0-9a-fA-F]{6}$/.test(record.hex_code)) {
    throw new Error(`CSV row ${lineNumber} has invalid hex value: "${record.hex_code}"`);
  }

  return {
    id: toInternalNumericId(record.id_dmc),
    code: record.id_dmc,
    name: record.name_dmc,
    nameMaxx: record.name_maxx,
    family: record.family_new.toLowerCase(),
    hex: record.hex_code.toLowerCase(),
  };
}

function formatColor(color) {
  return `{ id: ${color.id}, name: ${JSON.stringify(color.name)}, hex: ${JSON.stringify(color.hex)}, code: ${JSON.stringify(color.code)}, family: ${JSON.stringify(color.family)}, nameMaxx: ${JSON.stringify(color.nameMaxx)} }`;
}

function toInternalNumericId(code) {
  if (/^\d+$/.test(code)) {
    return Number(code);
  }

  const digitRun = code.match(/\d+/g)?.join("");
  if (digitRun) {
    return Number(digitRun);
  }

  let hash = 0;

  for (const character of code) {
    hash = (hash * 31 + character.charCodeAt(0)) % 100000;
  }

  return 900000 + hash;
}

function parseCsv(text) {
  const rows = [];
  let row = [];
  let value = "";
  let inQuotes = false;

  for (let index = 0; index < text.length; index += 1) {
    const character = text[index];
    const nextCharacter = text[index + 1];

    if (character === '"') {
      if (inQuotes && nextCharacter === '"') {
        value += '"';
        index += 1;
        continue;
      }

      inQuotes = !inQuotes;
      continue;
    }

    if (!inQuotes && character === ",") {
      row.push(value);
      value = "";
      continue;
    }

    if (!inQuotes && (character === "\n" || character === "\r")) {
      if (character === "\r" && nextCharacter === "\n") {
        index += 1;
      }

      row.push(value);
      rows.push(row);
      row = [];
      value = "";
      continue;
    }

    value += character;
  }

  if (inQuotes) {
    throw new Error("CSV ended while inside a quoted field");
  }

  if (value.length > 0 || row.length > 0) {
    row.push(value);
    rows.push(row);
  }

  return rows;
}

const GENERATED_HEADER = `// This file is generated by scripts/generate-dmc-colors.mjs
// Source of truth: data/thread-colors.csv
// Do not edit this file directly.
`;

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
